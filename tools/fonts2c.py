#!/usr/bin/env python3
"""Convert BDF pixel fonts to C (main/fonts.c) for the on-device apps.

Glyphs are rendered through Pillow's bitmap-font path - the same one the Python
tidbyt-server uses - so text drawn on the device matches the server pixel for pixel.

Usage: python tools/fonts2c.py <dir with .bdf files>
"""

import sys
from pathlib import Path

from PIL import BdfFontFile, Image, ImageDraw, ImageFont

FONTS = [  # (bdf name, C identifier)
    ("tb-8", "font_tb8"),
    ("6x13", "font_6x13"),
    ("10x20", "font_10x20"),
    ("CG-pixel-4x5-mono", "font_4x5"),
]
FIRST, LAST = 32, 255  # printable ASCII + Latin-1 (umlauts, degree sign, ...)


def load(bdf_dir: Path, name: str) -> ImageFont.ImageFont:
    pil = bdf_dir / f"{name}.pil"
    if not pil.exists():
        with open(bdf_dir / f"{name}.bdf", "rb") as fp:
            BdfFontFile.BdfFontFile(fp).save(str(bdf_dir / name))
    return ImageFont.load(str(pil))


def glyph_rows(font, ch, height):
    """Rows of a glyph cell as ints, MSB = leftmost pixel; (advance, rows)."""
    adv = font.getbbox(ch)[2]
    if adv == 0:
        return 0, []
    img = Image.new("1", (adv, height), 0)
    ImageDraw.Draw(img).text((0, 0), ch, font=font, fill=1)
    rows = []
    for y in range(height):
        bits = 0
        for x in range(adv):
            if img.getpixel((x, y)):
                bits |= 1 << (15 - x)
        rows.append(bits)
    return adv, rows


def main():
    bdf_dir = Path(sys.argv[1])
    out = [
        "// Generated by tools/fonts2c.py - do not edit.",
        '#include "fonts.h"',
        "",
    ]
    for name, ident in FONTS:
        font = load(bdf_dir, name)
        height = font.getbbox("A")[3]
        glyphs, rows = [], []
        for code in range(FIRST, LAST + 1):
            ch = bytes([code]).decode("latin-1")
            adv, cell = glyph_rows(font, ch, height)
            if adv > 16:
                raise SystemExit(f"{name}: glyph {code} is wider than 16 px")
            glyphs.append((adv, len(rows)))
            rows.extend(cell)
        out.append(f"static const uint16_t {ident}_rows[] = {{")
        for i in range(0, len(rows), 12):
            out.append("    " + ", ".join(f"0x{r:04x}" for r in rows[i:i + 12]) + ",")
        out.append("};")
        out.append(f"static const font_glyph_t {ident}_glyphs[] = {{")
        for i in range(0, len(glyphs), 6):
            out.append("    " + ", ".join(f"{{{a}, {o}}}" for a, o in glyphs[i:i + 6]) + ",")
        out.append("};")
        out.append(f"const font_t {ident} = {{{height}, {FIRST}, {LAST}, {ident}_glyphs, {ident}_rows}};")
        out.append("")
        print(f"{name}: height {height}, {len(rows) * 2 + len(glyphs) * 4} bytes")
    dest = Path(__file__).resolve().parent.parent / "main" / "fonts.c"
    dest.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {dest}")


if __name__ == "__main__":
    main()
